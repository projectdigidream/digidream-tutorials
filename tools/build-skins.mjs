#!/usr/bin/env node
// Dress the tutorial site in the shipped uikit skins (uikit/skins/
// index.json "ship"). Each skin is compiled by uikit's own compiler, so the
// colours, fonts, radii, bevels and patterns are the ones the tools wear.
//
//   node tutorials/tools/build-skins.mjs
//
// Writes assets/skins/skins.css (one rule per skin and mode: the site's own
// variables mapped from the skin's tokens, plus every token as --dnp-*),
// assets/skins/skins.js (the list the skin picker shows) and copies the
// skins' font files. Re-run when a skin changes.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const UIKIT = path.resolve(here, '../../uikit');
const OUT = path.resolve(here, '../assets/skins');
const { loadChain, compile, parseColor } = await import(path.join(UIKIT, 'lib/skin.js'));

const source = { read: async (p) => { try { return fs.readFileSync(path.join(UIKIT, p), 'utf8'); } catch { return null; } } };
const ship = JSON.parse(fs.readFileSync(path.join(UIKIT, 'skins/index.json'), 'utf8')).ship;

// The site's variables (assets/site.css) and the skin token each comes from.
const MAP = {
  bg: 'color.bg.app', rail: 'color.bg.rail', panel: 'color.bg.panel', raised: 'color.bg.raised', hover: 'color.bg.hover',
  input: 'color.bg.input', code: 'color.bg.code', sunken: 'color.bg.sunken',
  'line-soft': 'color.line.soft', line: 'color.line.main', 'line-strong': 'color.line.strong',
  text: 'color.text.primary', 'text-2': 'color.text.secondary', 'text-dim': 'color.text.dim',
  accent: 'color.accent', 'accent-hover': 'color.accentHover', 'accent-ink': 'color.accentInk', select: 'color.select',
  ok: 'color.ok', warn: 'color.warn', error: 'color.error', info: 'color.info', wave: 'color.wave',
  when: 'color.tone.when', if: 'color.tone.if', then: 'color.tone.then',
  shadow: 'shadow.menu', font: 'font.ui', mono: 'font.mono',
  'r-s': 'radius.small', 'r-c': 'radius.control', 'r-card': 'radius.card', 'r-d': 'radius.dialog',
};
const px = (k, v) => (typeof v === 'number' && /^(size|radius|space)\./.test(k) ? `${v}px` : v);
const luminance = (c) => { const p = parseColor(String(c)); if (!p) return 0; const [r, g, b] = p; return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255; };

fs.mkdirSync(OUT, { recursive: true });
const css = [`/* GENERATED by tutorials/tools/build-skins.mjs from uikit/skins (${ship.join(', ')}). Do not edit. */`];
const list = [];
for (const name of ship) {
  const warnings = [];
  const { merged } = await loadChain(name, source, warnings);
  const c = compile(merged, { warnings });
  if (warnings.length) { console.error(`skin ${name}: ${warnings.length} problem(s)\n  ${warnings.join('\n  ')}`); process.exit(1); }
  for (const f of c.fonts) {
    // The compiler resolves a font's path against uikit/ (skins/<name>/fonts/…).
    const from = path.join(UIKIT, f.file);
    const to = path.join(OUT, name, path.basename(f.file));
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.copyFileSync(from, to);
    const lic = path.join(path.dirname(from), 'OFL.txt');
    if (fs.existsSync(lic)) fs.copyFileSync(lic, path.join(path.dirname(to), 'OFL.txt'));
    css.push(`@font-face { font-family: "${f.family}"; src: url("${name}/${path.basename(f.file)}"); font-weight: ${f.weight ?? 400}; font-style: ${f.style ?? 'normal'}; font-display: swap; }`);
  }
  const modes = [];
  for (const mode of c.modes) {
    const t = c.tokens[`${mode}/mouse`];
    const dark = luminance(t['color.bg.app']) < 0.5;
    const decl = [`color-scheme: ${dark ? 'dark' : 'light'}`];
    // A font that draws ligatures wrongly says so (ps1's pixel font turns "fi" into one glyph).
    if (c.fonts.some(f => f.ligatures === false)) decl.push('font-variant-ligatures: none');
    for (const [v, k] of Object.entries(MAP)) if (t[k] !== undefined) decl.push(`--${v}: ${px(k, t[k])}`);
    for (const [k, v] of Object.entries(t)) if (typeof v === 'string' || typeof v === 'number') decl.push(`--dnp-${k.replace(/\./g, '-')}: ${px(k, v)}`);
    css.push(`:root[data-skin="${name}"][data-skin-mode="${mode}"] { ${decl.join('; ')}; }`);
    modes.push({ id: mode, dark, swatches: [t['color.bg.app'], t['color.bg.panel'], t['color.accent'], t['color.text.primary'], t['color.select']] });
  }
  // `font:` shorthands reset font-variant-ligatures, so a root setting alone is
  // lost on the body and every control; say it on every element.
  if (c.fonts.some(f => f.ligatures === false)) css.push(`:root[data-skin="${name}"] *, :root[data-skin="${name}"] *::before, :root[data-skin="${name}"] *::after { font-variant-ligatures: none; font-feature-settings: "liga" 0, "clig" 0, "dlig" 0; }`);
  list.push({ id: name, name: c.name, about: c.about, modes });
  console.log(`${name}: ${c.modes.join(', ')}`);
}
fs.writeFileSync(path.join(OUT, 'skins.css'), css.join('\n') + '\n');
fs.writeFileSync(path.join(OUT, 'skins.js'), `// GENERATED by tutorials/tools/build-skins.mjs. Do not edit.\nwindow.DNP_SKINS = ${JSON.stringify(list, null, 1)};\n`);
console.log(`assets/skins/skins.css ${(fs.statSync(path.join(OUT, 'skins.css')).size / 1024).toFixed(0)} KB`);
