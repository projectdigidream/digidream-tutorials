#!/usr/bin/env node
// Copy the engine's generated vocabularies into the tutorial site, so the
// reference pages (reference/graph-nodes.html, monster-vocab.html,
// weapon-vocab.html) always show what the engine actually accepts.
// Run after the vocabulary changes:  node tutorials/tools/build-vocab.mjs
// The output is a classic script per vocabulary (works from file:// too).
//
// It reads the engine at a commit, HEAD by default (--rev <commit> for
// another), not its working tree: the tutorials teach what the engine has
// committed, never another session's work in progress. --worktree reads the
// files as they are on disk.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.resolve(here, '../../engine/maps/scripts');
const OUT = path.resolve(here, '../assets/data');
fs.mkdirSync(OUT, { recursive: true });

const args = process.argv.slice(2);
const worktree = args.includes('--worktree');
const rev = args.includes('--rev') ? args[args.indexOf('--rev') + 1] : 'HEAD';
const ENGINE = path.resolve(SRC, '../..');
const readSrc = (name) => worktree
  ? fs.readFileSync(path.join(SRC, name), 'utf8')
  : execFileSync('git', ['-C', ENGINE, 'show', `${rev}:maps/scripts/${name}`], { encoding: 'utf8', maxBuffer: 64 << 20 });
console.log(worktree ? 'engine: working tree' : `engine: ${rev} (${execFileSync('git', ['-C', ENGINE, 'rev-parse', '--short', rev], { encoding: 'utf8' }).trim()})`);

for (const name of ['graph', 'mob', 'weapon']) {
  const data = JSON.parse(readSrc(`${name}_vocab.json`));
  const js = `// GENERATED by tutorials/tools/build-vocab.mjs from engine/maps/scripts/${name}_vocab.json. Do not edit.\n` +
    `window.DNP_VOCAB = window.DNP_VOCAB || {};\nwindow.DNP_VOCAB[${JSON.stringify(name)}] = ${JSON.stringify(data)};\n`;
  fs.writeFileSync(path.join(OUT, `vocab-${name}.js`), js);
  console.log(`assets/data/vocab-${name}.js  ${(js.length / 1024).toFixed(0)} KB`);
}
