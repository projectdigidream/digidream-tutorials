#!/usr/bin/env node
// Copy the engine's generated vocabularies into the tutorial site, so the
// reference pages (reference/graph-nodes.html, monster-vocab.html,
// weapon-vocab.html) always show what the engine actually accepts.
// Run after the vocabulary changes:  node tutorials/tools/build-vocab.mjs
// The output is a classic script per vocabulary (works from file:// too).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.resolve(here, '../../engine/maps/scripts');
const OUT = path.resolve(here, '../assets/data');
fs.mkdirSync(OUT, { recursive: true });

for (const name of ['graph', 'mob', 'weapon']) {
  const file = path.join(SRC, `${name}_vocab.json`);
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  const js = `// GENERATED by tutorials/tools/build-vocab.mjs from engine/maps/scripts/${name}_vocab.json. Do not edit.\n` +
    `window.DNP_VOCAB = window.DNP_VOCAB || {};\nwindow.DNP_VOCAB[${JSON.stringify(name)}] = ${JSON.stringify(data)};\n`;
  fs.writeFileSync(path.join(OUT, `vocab-${name}.js`), js);
  console.log(`assets/data/vocab-${name}.js  ${(js.length / 1024).toFixed(0)} KB`);
}
